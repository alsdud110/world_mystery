/// Puzzle Engine 2.0 PART 3C: a timeline planned, checked and generated by
/// the season factory's own tools — on a copy of Rome (every case written
/// at every level) with Case 08 Mission 3 made a timeline, and on the
/// test-only sandbox season `s8_timeline` (its plans under
/// `test/sandbox/plans/`, played in the app by `test/sandbox/timeline_season_test.dart`).
void main() {
  const trial = 'content_pipeline/seasons/s3_rome';
  const s8 = 'test/sandbox/plans/s8_timeline';
  late Directory tmp;
  late String dir;

  setUp(() {
    tmp = Directory.systemTemp.createTempSync('timeline_generation_');
    dir = '${tmp.path.replaceAll(r'\', '/')}/$trial';
    for (final f in Directory(trial).listSync(recursive: true).whereType<File>()) {
      File('${tmp.path}/${f.path.replaceAll(r'\', '/')}')
        ..createSync(recursive: true)
        ..writeAsBytesSync(f.readAsBytesSync());
    }
  });
  tearDown(() => tmp.deleteSync(recursive: true));

  group('Rome with a timeline', () {
    test('every check of the planner holds; the reasoning is left to a person, said', () {
      makeRomeTimeline(dir);
      final r = SeasonQuality.run(dir);
      expect([for (final f in r.findings) if (f.isError) '$f'], isEmpty);
      final review = r.findings.where((f) => f.code == 'timeline_reasoning_review').toList();
      expect(review, hasLength(1));
      expect([review.single.level, review.single.where], [Level.info, 'cases/$romeTimelineCase $romeTimelineMission']);
      expect(review.single.message, contains("a person's reading"));
    });

    test('its levels are written and the same game: one order, the same cards and times', () {
      makeRomeTimeline(dir);
      final season = PlanFiles.loadSeasonPlan('$dir/season.plan.json');
      expect(CaseLevels.checkCase('$dir/cases/$romeTimelineCase/case.plan.json', season, SchemaSet.load('tool/season_gen/schema')), isEmpty);
    });

    test('a level whose row of the diary no longer holds a relation\'s line: refused at that level', () {
      makeRomeTimeline(dir);
      final file = File('$dir/cases/$romeTimelineCase/levels.json');
      final levels = jsonDecode(file.readAsStringSync()) as Map;
      final line = (levels['lines'] as List).cast<Map>().firstWhere((l) => (l['rookie'] as String).startsWith('FRIDAY, MIDNIGHT — I turned'));
      line['master'] = 'FRIDAY, MIDNIGHT — I left with the copy.';
      file.writeAsStringSync(jsonEncode(levels));
      final season = PlanFiles.loadSeasonPlan('$dir/season.plan.json');
      expect(CaseLevels.checkCase('$dir/cases/$romeTimelineCase/case.plan.json', season, SchemaSet.load('tool/season_gen/schema')).join('\n'),
          contains('timeline_line_unread'));
    });

    test('generated: its timeline at Rookie, Junior and Master, the same order and anchors', () {
      makeRomeTimeline(dir);
      Generated make() => CaseGenerator.sandbox(seasonPath: '$dir/season.plan.json', casePaths: SeasonCases.of('$dir/season.plan.json'));
      final made = make();
      final own = made.files['$romeTimelineCase.g.dart']!;
      final levels = made.files['${romeTimelineCase}_levels.g.dart']!;
      expect(own, allOf(contains("'$romeTimelineMission': TimelineSpec("), contains("text: 'Livia finds the piece is too light.'"), contains("anchor: 'TUESDAY'")));
      expect(levels, allOf(contains("text: 'Livia notices the piece is too light.'"), contains("text: 'Livia discovers the piece weighs far too little.'")));
      expect(RegExp("anchor: 'TUESDAY'").allMatches(levels), hasLength(2), reason: 'the day fixed at Junior and at Master too');
      expect(RegExp(r"order: \[\s*'tuesday',\s*'thursday',\s*'friday_am',\s*'midnight',\s*\]").allMatches(levels), hasLength(2));
      expect(made.files['s3_rome_levels.g.dart'], contains('timelines: {'));
      expect(make().files, made.files, reason: 'the same plans, the same bytes');
    });

    test('Rome as it is: no timeline table in any file it makes', () {
      final made = CaseGenerator.sandbox(seasonPath: '$trial/season.plan.json', casePaths: SeasonCases.of('$trial/season.plan.json'));
      for (final MapEntry(:key, :value) in made.files.entries) {
        expect(value, isNot(anyOf(contains('TimelineSpec'), contains('timelines:'), contains('Timelines'))), reason: key);
      }
    });
  });

  group('a timeline plan the factory refuses', () {
    final season = PlanFiles.loadSeasonPlan('$s8/season.plan.json');
    Map<String, dynamic> base() => jsonDecode(File('$s8/cases/s8_ep01/case.plan.json').readAsStringSync()) as Map<String, dynamic>;

    /// The codes of the sandbox's timeline once [change] is made to its mission (`format` when it does not read).
    List<String> codes(void Function(Map<String, dynamic> m, Map<String, dynamic> t, List<Map<String, dynamic>> cards) change) {
      final json = base();
      final m = (json['missions'] as List)[1] as Map<String, dynamic>;
      final t = (m['play'] as Map<String, dynamic>)['timeline'] as Map<String, dynamic>;
      change(m, t, (t['cards'] as List).cast<Map<String, dynamic>>());
      void sync() => (m['puzzle']['answerSpec'] as Map)['options'] = [for (final c in t['cards'] as List) {'id': c['id'], 'label': c['title']}];
      if (!(m['keepOptions'] == true)) sync();
      m.remove('keepOptions');
      final CasePlan plan;
      try {
        plan = CasePlan.fromJson(json);
      } on PlanFormatException {
        return ['format'];
      }
      return [for (final i in PlayCheck.casePlan(plan, season)) i.code];
    }

    Map<String, dynamic> card(String id, {bool discard = false}) => {'id': id, 'title': id.toUpperCase(), 'text': 'Something.', if (discard) 'discard': true};

    test('the sandbox\'s own: none', () {
      expect(codes((_, _, _) {}), isEmpty);
    });

    test('too many cards to place, to set aside; none fixed', () {
      expect(codes((m, t, cards) => cards.insertAll(1, [for (final x in ['a', 'b', 'c', 'd']) card(x)])), contains('timeline_size'), reason: '6 to place is the most');
      expect(codes((m, t, cards) => cards.addAll([card('x', discard: true), card('y', discard: true)])), contains('timeline_size'), reason: '2 aside at most');
      expect(codes((m, t, cards) => cards.first.remove('anchor')), contains('timeline_size'), reason: 'one card at least is fixed by its time');
      expect(codes((m, t, cards) => cards.addAll([for (var i = 0; i < 7; i++) card('z$i', discard: true)])), ['format'], reason: '11 cards at most');
    });

    test('two orders the words allow; a card no line orders', () {
      final found = codes((m, t, cards) => (t['relations'] as List).removeLast());
      expect(found, containsAll(['timeline_ambiguous', 'timeline_card_unrelated']));
    });

    test('a relation against the order; a card set aside in the order', () {
      expect(codes((m, t, cards) => ((t['relations'] as List).first as Map)..['earlier'] = 'bell'..['later'] = 'tom'), contains('timeline_relation_contradicts'));
      expect(codes((m, t, cards) => (m['puzzle']['answerSpec'] as Map)['answer'] = 'key,tom,bell,cat'), contains('timeline_order_mismatch'));
      expect(codes((m, t, cards) => (m['puzzle']['answerSpec'] as Map)['codeLength'] = 5), contains('timeline_order_mismatch'));
    });

    test('options that are not the cards; a relation\'s line the player never reads; no wrong-order line', () {
      expect(codes((m, t, cards) {
        m['keepOptions'] = true;
        ((m['puzzle']['answerSpec'] as Map)['options'] as List).removeLast();
      }), contains('timeline_options_mismatch'));
      expect(codes((m, t, cards) => ((t['relations'] as List).first as Map)['line'] = 'Mr. Bell was late.'), contains('timeline_line_unread'));
      expect(codes((m, t, cards) => (m['play'] as Map).remove('orderFeedback')), contains('play_field_missing'));
    });

    test('a card named as a plan\'s id; a timeline without its scene, or on another puzzle', () {
      expect(codes((m, t, cards) {
        cards[1]['id'] = 's8_ep01_m1';
        ((t['relations'] as List).first as Map)['earlier'] = 's8_ep01_m1';
        (m['puzzle']['answerSpec'] as Map)['answer'] = 'key,s8_ep01_m1,bell,lee';
      }), contains('id_reserved'));
      expect(codes((m, t, cards) => (m['play'] as Map).remove('timeline')), contains('play_field_missing'));
      expect(codes((m, t, cards) => (m['puzzle'] as Map)..['paletteId'] = 'order_sequence'..['engineTable'] = null), contains('play_scene_mismatch'));
    });
  });
}
